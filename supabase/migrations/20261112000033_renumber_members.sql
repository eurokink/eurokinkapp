-- Numéros de membre consécutifs (les essais annulés avaient consommé des numéros)
alter table public.profiles alter column member_number set generated by default;
with r as (select id, row_number() over (order by created_at, member_number) n from public.profiles)
update public.profiles p set member_number = r.n from r where r.id = p.id and p.member_number <> r.n;
select setval('public.profiles_member_number_seq', (select coalesce(max(member_number), 0) from public.profiles) + 1, false);
alter table public.profiles alter column member_number set generated always;
