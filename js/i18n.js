// Ville : traduite si connue, sinon gardée telle quelle
const tc = (s) => tr(s) || s;

export function t(s) {
  if (LANG === 'fr' || s == null) return s;
  const raw = String(s);
  const core = raw.trim();
  if (!core || !/[A-Za-zÀ-ÿ]/.test(core)) return raw;
  const wrap = (x) => raw.replace(core, x);
  const exact = tr(core);
  if (exact != null) return wrap(exact);
  if (core.length > 2 && core === core.toUpperCase() && /[A-ZÀ-Ý]/.test(core)) {
    const k = Object.keys(T).find((x) => x.toUpperCase() === core);
    if (k) return wrap(tr(k).toUpperCase());
  }
  for (const [re, f] of R) { const m = core.match(re); if (m) return wrap(f(m)[I]); }
  if (/^· (.+)$/.test(core)) { const x = t(core.slice(2)); if (x !== core.slice(2)) return wrap('· ' + x); }
  if (/^[^,\s]+(?: [^,\s]+){0,2}(, [^,\s]+(?: [^,\s]+){0,2})+$/.test(core)) {
    const parts = core.split(', '); const out = parts.map((p) => tr(p) || p);
    if (out.some((o, i) => o !== parts[i])) return wrap(out.join(', '));
  }
  if (core.includes(' · ')) {
    const parts = core.split(' · ');
    const out = parts.map((p) => t(p));
    if (out.some((o, i) => o !== parts[i])) return wrap(out.join(' · '));
  }
  // Début ou fin de phrase connue suivie/précédée d'un nom (ex. « Ta demande pour « X » a bien été reçue le … »)
  return raw;
}

// Traduction de l'affichage : textes et attributs visibles, sauf champs de saisie et contenu marqué data-no-i18n
const ATTRS = ['placeholder', 'aria-label', 'title', 'label'];
function walk(root) {
  if (LANG === 'fr' || !root) return;
  if (root.nodeType === 3) { fixText(root); return; }
  if (root.nodeType !== 1) return;
  const tw = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  let n = root;
  while (n) {
    if (n.nodeType === 1) {
      if (n.closest && n.closest('script, style, [data-no-i18n], [contenteditable]')) { n = tw.nextNode(); continue; }
      ATTRS.forEach((a) => { if (n.hasAttribute && n.hasAttribute(a)) { const v = n.getAttribute(a); const x = t(v); if (x !== v) n.setAttribute(a, x); } });
    } else fixText(n);
    n = tw.nextNode();
  }
}
function fixText(node) {
  const p = node.parentElement;
  if (!p || p.closest('textarea, script, style, [data-no-i18n], [contenteditable]')) return;
  const v = node.nodeValue; const x = t(v);
  if (x !== v) node.nodeValue = x;
}
let busy = false;
export function startI18n() {
  if (LANG === 'fr') return;
  walk(document.body);
  new MutationObserver((list) => {
    if (busy) return;
    busy = true;
    try {
      list.forEach((m) => {
        if (m.type === 'characterData') fixText(m.target);
        else if (m.type === 'attributes') { const v = m.target.getAttribute(m.attributeName); const x = t(v); if (x !== v) m.target.setAttribute(m.attributeName, x); }
        else m.addedNodes.forEach(walk);
      });
    } finally { busy = false; }
  }).observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRS });
}
